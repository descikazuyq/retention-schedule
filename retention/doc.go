// Package retention 提供在本机运行的档案保管期限与销毁清册功能。
//
// 调用 Open 选择一个本地保存位置后，可以：
//   - Register 登记档案条目（只登记元数据，不读取或保存真实文件）；
//   - Freeze / Release 记录同一档案的多条冻结及解除，解除不删除记录；
//   - Check 在销毁前只做核对，一次看清整批所有阻碍，不销毁、不写清册、不占用申请编号；
//   - Destroy 一次选择多个档案办理销毁，全部满足条件才生成已关闭清册；
//   - History 按档案编号核对登记内容、全部冻结解除历史、当前状态与对应清册；
//   - GetManifest 按申请编号取回已关闭清册。
//
// 所有日期统一为 YYYY-MM-DD（见 ParseDate 与 Date），按日历日期比较，
// 不受时区或夏令时影响。
//
// 状态保存在所选目录下的 JSON 文件中，采用临时文件加原子替换写入；
// 同一位置被本机上的多个程序同时打开时，通过文件锁串行化每次办理，
// 先成功者生效，关闭后重新打开记录仍完整可查。
